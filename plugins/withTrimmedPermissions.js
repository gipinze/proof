const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/**
 * Permission hygiene.
 *
 * `expo-media-library` declares READ_MEDIA_AUDIO / VIDEO / IMAGES plus the
 * partial-access variant. This app only ever *writes* one PNG, so on Android
 * 10+ it needs none of them — but with them in the manifest the first save
 * opens "Allow Proof to access music and audio", which is alarming and untrue.
 * The photo permission stays: it is what "save to gallery" honestly needs, and
 * the runtime request only fires if the unpermissioned MediaStore write fails.
 *
 * React Native's *debug* manifest adds ACCESS_LOCAL_NETWORK (Android 17) so its
 * dev overlay can draw over other apps; that one pops "Allow Proof to find,
 * connect to, and determine the position of nearby devices" on a fresh debug
 * install. Debug builds reach Metro over `adb reverse`, so we strip it in a
 * debug-only manifest overlay.
 */

const REMOVE_ALWAYS = [
  'android.permission.READ_MEDIA_AUDIO',
  'android.permission.READ_MEDIA_VIDEO',
  'android.permission.READ_MEDIA_VISUAL_USER_SELECTED',
  // Expo's template declares "draw over other apps" for the dev overlay; it is
  // meaningless in a release build and Play flags it. React Native's *debug*
  // manifest adds it back where it is actually needed.
  'android.permission.SYSTEM_ALERT_WINDOW',
];

const DEBUG_MANIFEST = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by plugins/withTrimmedPermissions.js -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">

    <!-- React Native's dev support adds this for the in-app dev overlay. Proof
         reaches Metro through adb reverse, and the permission prompts "nearby
         devices" on every fresh debug install, so drop it. -->
    <uses-permission
        android:name="android.permission.ACCESS_LOCAL_NETWORK"
        tools:node="remove" />

    <!-- Debug builds fetch the JS bundle over plain HTTP from Metro. Android 9+
         blocks cleartext by default, which shows up as "Unable to load script". -->
    <application android:usesCleartextTraffic="true" />

</manifest>
`;

function withTrimmedMainManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults;
    const permissions = manifest.manifest['uses-permission'] || [];

    manifest.manifest['uses-permission'] = permissions.filter(
      (entry) => !REMOVE_ALWAYS.includes(entry.$['android:name']),
    );

    const hasLegacyWrite = manifest.manifest['uses-permission'].some(
      (entry) => entry.$['android:name'] === 'android.permission.WRITE_EXTERNAL_STORAGE',
    );
    if (!hasLegacyWrite) {
      manifest.manifest['uses-permission'].push({
        $: {
          'android:name': 'android.permission.WRITE_EXTERNAL_STORAGE',
          'android:maxSdkVersion': '28',
        },
      });
    }

    return cfg;
  });
}

function withDebugManifest(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const debugDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'debug');
      fs.mkdirSync(debugDir, { recursive: true });
      fs.writeFileSync(path.join(debugDir, 'AndroidManifest.xml'), DEBUG_MANIFEST);
      return cfg;
    },
  ]);
}

module.exports = function withTrimmedPermissions(config) {
  config = withTrimmedMainManifest(config);
  config = withDebugManifest(config);
  return config;
};
